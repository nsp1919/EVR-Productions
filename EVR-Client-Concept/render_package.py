"""Render and verify the local EVR concept deliverables."""
from pathlib import Path
import json
import subprocess
import wave
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parent
ASSETS = ROOT / "assets"
ASSETS.mkdir(exist_ok=True)
REPORT = []


def check(condition, message):
    if not condition:
        raise AssertionError(message)
    REPORT.append(message)


with sync_playwright() as pw:
    browser = pw.chromium.launch(channel="msedge", headless=True)
    page = browser.new_page(viewport={"width": 1440, "height": 1000}, device_scale_factor=1)
    page.emulate_media(reduced_motion="reduce")
    errors = []
    page.on("pageerror", lambda error: errors.append(str(error)))
    base = (ROOT / "index.html").as_uri()
    page.goto(base)
    for route in ["home", "weddings", "corporate", "request", "estimate", "process", "services", "approach", "brand-work", "production-quote", "studio"]:
        page.goto(base + "#/" + route)
        page.locator("#" + route).wait_for(state="visible")
        page.wait_for_function("scrollY === 0")
        page.screenshot(path=str(ASSETS / f"{route}-desktop.png"))
        check(page.evaluate("document.documentElement.scrollWidth <= innerWidth"), f"No desktop overflow: {route}")
    page.goto(base + "#/home")
    page.wait_for_function("scrollY === 0")
    page.screenshot(path=str(ASSETS / "home-full-layout.png"), full_page=True)
    page.goto(base + "#/estimate")
    check("Discussed on a call" in page.locator("#estimate-breakdown").inner_text() and "INR" not in page.locator("#estimate-breakdown").inner_text(), "Wedding request has no public prices")
    page.locator("#estimate-type").select_option("corporate")
    check(page.locator("#estimate-breakdown dd").all_text_contents() == ["1", "Requested", "3", "Discussed on a call"], "Corporate request shows quantities rather than prices")
    page.locator("#estimate-days").fill("2")
    check(page.locator("#estimate-breakdown dd").first.inner_text() == "2", "Public request reflects two shoot days")
    page.locator("#estimate-days").fill("0")
    check(page.locator("#estimate-request").is_disabled(), "Public estimate rejects zero days")
    page.locator("#estimate-days").fill("2")
    page.locator("#estimate-request").click()
    page.locator("#request").wait_for(state="visible")
    check(page.locator("#request").is_visible(), "Public estimate leads to enquiry form")
    check("2 shoot day(s)" in page.locator('[name="brief"]').input_value() and "INR" not in page.locator('[name="brief"]').input_value(), "Scope without prices carries into enquiry")
    page.goto(base + "#/studio")
    check(page.locator("#total").inner_text() == "INR 57,000.00", "Wedding default total = INR 57,000")
    page.locator("#quote-type").select_option("corporate")
    check(page.locator("#total").inner_text() == "INR 45,500.00", "Corporate default total = INR 45,500")
    page.locator("#discount").fill("500")
    page.locator("#tax").fill("18")
    check(page.locator("#total").inner_text() == "INR 53,100.00", "Discount then tax calculation = INR 53,100")
    page.locator("#discount").fill("999999")
    check(page.locator("#preview-quote").is_disabled(), "Excessive discount blocks preview")
    page.locator("#discount").fill("500")
    page.locator("#quote-rows input").first.fill("-1")
    check(page.locator("#preview-quote").is_disabled(), "Negative quantity blocks preview")
    page.locator("#quote-rows input").first.fill("1")
    page.locator("#quote-client").fill("Demo Draft")
    page.locator("#save-draft").click()
    check("saved" in page.locator("#quote-status").inner_text(), "Browser draft save reports success")
    page.reload()
    page.locator("#load-draft").click()
    check(page.locator("#quote-client").input_value() == "Demo Draft", "Browser draft survives reload")
    check(page.locator("#total").inner_text() == "INR 53,100.00", "Draft preserves quantities, prices, discount and tax")
    page.locator("#quote-client").fill("")
    page.locator("#preview-quote").click()
    check(not page.locator("#quote-dialog").is_visible(), "Missing client details block preview")
    page.locator("#quote-type").select_option("wedding")
    page.locator("#quote-client").fill("Sample Client")
    page.locator("#quote-ref").fill("EVR-SAMPLE-001")
    page.locator("#preview-quote").click()
    check(page.locator("#pdf-total strong").inner_text() == "Total: INR 57,000.00", "PDF preview matches quotation total")
    page.pdf(path=str(ROOT / "EVR-Sample-Quotation.pdf"), format="A4", print_background=True, prefer_css_page_size=True)
    quote = page.locator("#quote-document").evaluate("(element) => element.outerHTML")
    (ROOT / "sample-quotation.html").write_text(
        '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>EVR | Sample quotation</title><link rel="stylesheet" href="style.css"><style>body{background:#fffdf8}.quote-document{width:794px;min-height:1123px;margin:auto;padding:48px} @media(max-width:794px){.quote-document{width:100%}} @media print{body>.quote-document{display:block!important;width:100%;min-height:0;padding:0}}</style></head><body>' + quote + "</body></html>",
        encoding="utf-8",
    )
    page.locator("#close-quote").click()
    page.evaluate("localStorage.removeItem('evr-concept-draft')")
    page.goto(base + "#/request")
    page.locator("#inquiry-form button").click()
    check(page.locator("#inquiry-status").inner_text() == "", "Empty required enquiry fields prevent submission")
    page.locator('[name="name"]').fill("Sample Client")
    page.locator('[name="phone"]').fill("0000000000")
    page.locator('[name="location"]').fill("Sample venue")
    page.locator('[name="brief"]').fill("Sample requirements only")
    page.locator("#inquiry-form button").click()
    check("Nothing was transmitted" in page.locator("#inquiry-status").inner_text(), "Valid enquiry shows explicit demo-only confirmation")
    page.goto(base + "#/work")
    page.locator('#work [data-filter="wedding"]').click()
    check(page.locator('[data-category]:visible').count() == 1, "Wedding portfolio filter")
    page.goto(base + "#/brand-work")
    page.locator('#brand-work [data-filter="brand"]').click()
    check(page.locator('[data-category]:visible').count() == 1, "Corporate portfolio filter")
    page.locator('#brand-work [data-category="brand"] [data-project="brand"]').click()
    check(page.locator("#project-dialog").is_visible(), "Project-detail preview opens")
    check(page.locator("#project-title").inner_text() == "A brand, introduced", "Project-detail content matches selection")
    page.locator("#close-project").click()
    check(not page.locator("#project-dialog").is_visible(), "Project preview closes")
    mobile = browser.new_page(viewport={"width": 390, "height": 844}, device_scale_factor=1, is_mobile=True, has_touch=True)
    mobile.emulate_media(reduced_motion="reduce")
    for route in ["home", "weddings", "corporate", "work", "request", "estimate", "process", "services", "approach", "brand-work", "production-quote", "studio"]:
        mobile.goto(base + "#/" + route)
        mobile.wait_for_function("scrollY === 0")
        check(mobile.evaluate("document.documentElement.scrollWidth <= innerWidth"), f"No mobile document overflow: {route}")
        if route == "home":
            mobile.screenshot(path=str(ASSETS / "home-mobile.png"), full_page=True)
            check(not mobile.locator("#main-nav").is_visible(), "Mobile menu starts closed")
            mobile.locator("#menu-toggle").click()
            check(mobile.locator("#main-nav").is_visible(), "Mobile menu opens")
            mobile.locator('#main-nav a[href="#/weddings"]').click()
            mobile.locator("#weddings").wait_for(state="visible")
            mobile.locator("#main-nav").wait_for(state="hidden")
            check(mobile.locator("#weddings").is_visible() and not mobile.locator("#main-nav").is_visible(), "Mobile navigation routes and closes menu")
    mobile.goto(base + "#/studio")
    mobile.locator("#preview-quote").click()
    check(mobile.locator("#quote-dialog").is_visible(), "Mobile quotation preview opens")
    check(mobile.evaluate("document.querySelector('#quote-dialog').scrollWidth <= document.querySelector('#quote-dialog').clientWidth"), "Mobile quote dialog has no horizontal overflow")
    page.set_viewport_size({"width": 794, "height": 1123})
    page.goto((ROOT / "sample-quotation.html").as_uri())
    page.screenshot(path=str(ASSETS / "quotation-preview.png"), full_page=True)
    page.set_viewport_size({"width": 1600, "height": 900})
    page.goto((ROOT / "presentation.html").as_uri())
    page.wait_for_function("Array.from(document.images).every(image => image.complete && image.naturalWidth > 0)")
    page.locator(".controls").evaluate("(element) => element.style.visibility = 'hidden'")
    check(page.locator(".slide").count() == 5, "Presentation contains exactly five slides")
    for number in range(1, 6):
        slide = page.locator(f"#slide-{number}")
        check(slide.evaluate("(el) => el.scrollHeight <= el.clientHeight"), f"Slide {number} fits its canvas")
        footer_top = slide.locator(".footer").bounding_box()["y"]
        content = slide.locator(".split, .service-grid, .quote-layout").bounding_box()
        check(content["y"] + content["height"] <= footer_top - 5, f"Slide {number} content clears footer")
        slide.screenshot(path=str(ASSETS / f"slide-{number}.png"))
    page.pdf(path=str(ROOT / "EVR-Concept-Presentation.pdf"), print_background=True, prefer_css_page_size=True)
    page.goto((ROOT / "START-HERE.html").as_uri())
    page.pdf(path=str(ROOT / "EVR-Presentation-Guide.pdf"), format="A4", print_background=True, prefer_css_page_size=True)
    page.goto((ROOT / "REFERENCE-ANALYSIS-AND-PLAN.html").as_uri())
    page.pdf(path=str(ROOT / "EVR-Reference-Analysis-and-Plan.pdf"), format="A4", print_background=True, prefer_css_page_size=True)
    check(not errors, "No browser JavaScript errors during tested flows")
    browser.close()

(ROOT / "validation.json").write_text(json.dumps({"checks": REPORT, "passed": len(REPORT)}, indent=2), encoding="utf-8")
print(json.dumps({"passed": len(REPORT), "outputs": [str(path.name) for path in ROOT.glob("*.pdf")]}, indent=2))
